// Generates supabase/seed.sql from src/data/seed.json.
// Run with: npm run seed-sql
// The seed only fills empty tables, so running it twice never duplicates content.
import { readFile, writeFile } from 'node:fs/promises';

const seed = JSON.parse(await readFile(new URL('../src/data/seed.json', import.meta.url), 'utf8'));

const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  if (Array.isArray(v) && v.some((x) => typeof x === 'object')) return `${q(JSON.stringify(v))}::jsonb`;
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`;
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const out = [
  '-- Generated by scripts/gen-seed-sql.mjs from src/data/seed.json. Do not edit by hand.',
  '-- Run after schema.sql. Only fills tables that are still empty.',
  '',
];

// Profile: fill only while it has never been edited.
const p = { ...seed.profile };
delete p.id;
out.push(
  `update public.profile set ${Object.entries(p)
    .map(([k, v]) => `${k} = ${v === '' ? "''" : q(v)}`)
    .join(',\n  ')}\nwhere id = 1 and name = '';`,
  ''
);

for (const table of ['projects', 'posts', 'certifications', 'timeline', 'skills', 'services']) {
  const rows = seed[table] ?? [];
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  out.push(`insert into public.${table} (${cols.join(', ')})`);
  out.push(`select * from (values`);
  out.push(rows.map((r) => `  (${cols.map((c) => q(r[c])).join(', ')})`).join(',\n'));
  out.push(`) as v(${cols.join(', ')})`);
  out.push(`where not exists (select 1 from public.${table});`, '');
}

// Typed date columns need casts when coming from a VALUES list.
let sql = out.join('\n');
sql = sql.replace(/(\d{4}-\d{2}-\d{2})'/g, "$1'::date");

await writeFile(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('Wrote supabase/seed.sql');
